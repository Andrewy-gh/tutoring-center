ALTER TABLE credit_transactions
  DROP CONSTRAINT IF EXISTS credit_transactions_idempotency_key_unique,
  DROP CONSTRAINT IF EXISTS credit_transactions_nonzero_delta,
  DROP CONSTRAINT IF EXISTS credit_transactions_available_after_nonnegative,
  DROP CONSTRAINT IF EXISTS credit_transactions_pending_after_nonnegative,
  ADD COLUMN available_delta integer,
  ADD COLUMN pending_delta integer,
  ADD COLUMN available_after integer,
  ADD COLUMN pending_after integer,
  ADD COLUMN idempotency_key text,
  ADD COLUMN note text;

UPDATE credit_transactions
SET
  available_delta = amount,
  pending_delta = CASE
    WHEN type = 'reservation' THEN GREATEST(amount * -1, 0)
    ELSE 0
  END,
  available_after = balance_after,
  note = 'Legacy student_id=' || student_id;

WITH transaction_running_pending AS (
  SELECT
    id,
    sum(pending_delta) OVER (PARTITION BY parent_id ORDER BY created_at ASC, id ASC) AS running_pending_after
  FROM credit_transactions
)
UPDATE credit_transactions
SET pending_after = transaction_running_pending.running_pending_after
FROM transaction_running_pending
WHERE credit_transactions.id = transaction_running_pending.id;

