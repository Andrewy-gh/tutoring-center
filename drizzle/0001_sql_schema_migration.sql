CREATE TYPE subject_kind AS ENUM ('group', 'leaf');

ALTER TYPE transaction_type RENAME TO transaction_type_old;

CREATE TYPE transaction_type AS ENUM (
  'purchase',
  'reservation',
  'reservation_release',
  'session_debit',
  'refund',
  'adjustment',
  'cancellation_fee'
);

ALTER TABLE credit_transactions
  ALTER COLUMN type TYPE transaction_type
  USING (
    CASE
      WHEN type::text = 'Purchase' THEN 'purchase'
      WHEN type::text = 'Session Debit' AND session_id IS NOT NULL THEN 'reservation'
      WHEN type::text = 'Session Debit' THEN 'session_debit'
      WHEN type::text = 'Refund' THEN 'refund'
      WHEN type::text = 'Adjustment' THEN 'adjustment'
      WHEN type::text = 'Cancellation Fee' THEN 'cancellation_fee'
      ELSE lower(replace(type::text, ' ', '_'))
    END
  )::transaction_type;

DROP TYPE transaction_type_old;

