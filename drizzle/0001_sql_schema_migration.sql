CREATE TABLE subjects (
  id integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME subjects_new_id_seq) PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL,
  kind subject_kind NOT NULL,
  parent_subject_id integer,
  parent_subject_kind subject_kind,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT subjects_slug_unique UNIQUE (slug),
  CONSTRAINT subjects_id_kind_unique UNIQUE (id, kind),
  CONSTRAINT subjects_parent_name_unique UNIQUE (parent_subject_id, name),
  CONSTRAINT subjects_parent_subject_id_fkey FOREIGN KEY (parent_subject_id, parent_subject_kind) REFERENCES subjects (id, kind),
  CONSTRAINT subjects_parent_must_be_group CHECK (
    (
      parent_subject_id IS NULL
      AND parent_subject_kind IS NULL
    ) OR (
      parent_subject_id IS NOT NULL
      AND parent_subject_kind = 'group'
    )
  ),
  CONSTRAINT subjects_not_self_parent CHECK (parent_subject_id IS NULL OR parent_subject_id <> id)
);

CREATE UNIQUE INDEX subjects_root_name_unique ON subjects (name) WHERE parent_subject_id IS NULL;

CREATE TEMP TABLE canonical_subjects AS
WITH subject_candidates AS (
  SELECT
    1 AS source_priority,
    COALESCE(NULLIF(btrim(regexp_replace(category, '[[:space:]]+', ' ', 'g')), ''), 'Untitled Subject') AS display_name,
    created_at,
    updated_at
  FROM subjects_legacy
  UNION ALL
  SELECT
    2 AS source_priority,
    COALESCE(NULLIF(btrim(regexp_replace(subject, '[[:space:]]+', ' ', 'g')), ''), 'Untitled Subject') AS display_name,
    created_at,
    created_at AS updated_at
  FROM student_grades
),
ranked_subjects AS (
  SELECT
    lower(display_name) AS canonical_key,
    display_name,
    created_at,
    updated_at,
    source_priority,
    row_number() OVER (
      PARTITION BY lower(display_name)
      ORDER BY source_priority ASC, length(display_name) ASC, display_name ASC
    ) AS canonical_name_rank,
    min(created_at) OVER (PARTITION BY lower(display_name)) AS first_created_at,
    max(updated_at) OVER (PARTITION BY lower(display_name)) AS last_updated_at
  FROM subject_candidates
),
subject_representatives AS (
  SELECT
    canonical_key,
    display_name,
    first_created_at,
    last_updated_at,
    COALESCE(
      NULLIF(btrim(regexp_replace(lower(display_name), '[^a-z0-9]+', '-', 'g'), '-'), ''),
      'subject'
    ) AS slug_base
  FROM ranked_subjects
  WHERE canonical_name_rank = 1
),
slugged_subjects AS (
  SELECT
    canonical_key,
    display_name,
    first_created_at,
    last_updated_at,
    slug_base,
    row_number() OVER (PARTITION BY slug_base ORDER BY canonical_key ASC) AS slug_rank
  FROM subject_representatives
)
SELECT
  canonical_key,
  display_name AS name,
  CASE
    WHEN slug_rank = 1 THEN slug_base
    ELSE slug_base || '-' || slug_rank
  END AS slug,
  first_created_at AS created_at,
  last_updated_at AS updated_at
FROM slugged_subjects;

CREATE TEMP TABLE inserted_subjects (
  id integer NOT NULL,
  slug text NOT NULL
);

WITH inserted_rows AS (
  INSERT INTO subjects (name, slug, kind, parent_subject_id, parent_subject_kind, is_active, created_at, updated_at)
SELECT
  name,
  slug,
  'leaf'::subject_kind,
  NULL,
  NULL,
  true,
  created_at,
  updated_at
FROM canonical_subjects
  RETURNING id, slug
)
INSERT INTO inserted_subjects (id, slug)
SELECT id, slug
FROM inserted_rows;

ALTER TABLE canonical_subjects
  ADD COLUMN subject_id integer;

UPDATE canonical_subjects
SET subject_id = inserted_subjects.id
FROM inserted_subjects
WHERE canonical_subjects.slug = inserted_subjects.slug;

CREATE TABLE tutor_subjects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id integer NOT NULL REFERENCES tutors (id),
  subject_id integer NOT NULL,
  subject_kind subject_kind NOT NULL DEFAULT 'leaf',
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT tutor_subjects_tutor_id_subject_id_unique UNIQUE (tutor_id, subject_id),
  CONSTRAINT tutor_subjects_subject_id_subject_kind_fkey FOREIGN KEY (subject_id, subject_kind) REFERENCES subjects (id, kind),
  CONSTRAINT tutor_subjects_leaf_only CHECK (subject_kind = 'leaf')
);

CREATE TEMP TABLE subject_id_map AS
SELECT
  subjects_legacy.id AS legacy_subject_id,
  subjects_legacy.tutor_id,
  canonical_subjects.subject_id
FROM subjects_legacy
JOIN canonical_subjects
  ON canonical_subjects.canonical_key = lower(
    COALESCE(NULLIF(btrim(regexp_replace(subjects_legacy.category, '[[:space:]]+', ' ', 'g')), ''), 'Untitled Subject')
  );

INSERT INTO tutor_subjects (tutor_id, subject_id, subject_kind, created_at, updated_at)
SELECT
  subject_id_map.tutor_id,
  subject_id_map.subject_id,
  'leaf'::subject_kind,
  min(subjects_legacy.created_at) AS created_at,
  max(subjects_legacy.updated_at) AS updated_at
FROM subject_id_map
JOIN subjects_legacy
  ON subjects_legacy.id = subject_id_map.legacy_subject_id
GROUP BY subject_id_map.tutor_id, subject_id_map.subject_id;

WITH inferred_student_parents AS (
  SELECT
    student_id,
    min(parent_id) AS parent_id
  FROM sessions
  GROUP BY student_id
  HAVING count(DISTINCT parent_id) = 1
)
UPDATE students
SET parent_id = inferred_student_parents.parent_id
FROM inferred_student_parents
WHERE students.id = inferred_student_parents.student_id
  AND students.parent_id IS NULL;

