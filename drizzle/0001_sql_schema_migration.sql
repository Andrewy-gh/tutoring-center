WITH ranked_credit_balances AS (
  SELECT
    id,
    row_number() OVER (PARTITION BY parent_id ORDER BY updated_at DESC, created_at DESC, id DESC) AS balance_rank,
    sum(amount_available) OVER (PARTITION BY parent_id) AS total_available,
    sum(amount_pending) OVER (PARTITION BY parent_id) AS total_pending,
    min(created_at) OVER (PARTITION BY parent_id) AS first_created_at,
    max(updated_at) OVER (PARTITION BY parent_id) AS last_updated_at
  FROM credit_balances
)
UPDATE credit_balances
SET
  amount_available = ranked_credit_balances.total_available,
  amount_pending = ranked_credit_balances.total_pending,
  created_at = ranked_credit_balances.first_created_at,
  updated_at = ranked_credit_balances.last_updated_at
FROM ranked_credit_balances
WHERE credit_balances.id = ranked_credit_balances.id
  AND ranked_credit_balances.balance_rank = 1;

DELETE FROM credit_balances
WHERE id IN (
  SELECT id
  FROM (
    SELECT
      id,
      row_number() OVER (PARTITION BY parent_id ORDER BY updated_at DESC, created_at DESC, id DESC) AS balance_rank
    FROM credit_balances
  ) ranked_credit_balances
  WHERE balance_rank > 1
);

